const DICT: Record<Language, Record<I18nKey, string>> = { en, nl, fr };

export function translator(lang: Language) {
  return (key: I18nKey, vars: Record<string, string | number> = {}) =>
    DICT[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}
export type T = ReturnType<typeof translator>;
